import json
from pathlib import Path

repo_root = Path(__file__).resolve().parent.parent  # not the current folder: the script works from anywhere


def lua_string(text: str) -> str:
    """A Lua string literal. json.dumps is not one: it writes non-ASCII characters as \\uXXXX, which Lua does not understand.
    Non-ASCII characters stay as UTF-8 (the file is written as UTF-8), control characters become decimal escapes."""
    parts = ['"']
    for char in text:
        if char == "\\":
            parts.append("\\\\")
        elif char == '"':
            parts.append('\\"')
        elif ord(char) < 32 or ord(char) == 127:
            parts.append(f"\\{ord(char):03d}")
        else:
            parts.append(char)
    parts.append('"')
    return "".join(parts)


def render(data: dict) -> str:
    lines = [
        "-- Generated by scripts/generate_locations_json.py",
        "-- Do not edit manually.",
        "local locations_data = {}",
        "",
        f"locations_data.version = {lua_string(data['version'])}",
        f"locations_data.game = {lua_string(data['game'])}",
        f"locations_data.total_locations = {data['total_locations']}",
        "",
        "-- Row ID (0..50) to AP Location",
        "locations_data.row_id_to_location = {",
    ]

    for row_id, item in sorted(data["row_id_to_location"].items(), key=lambda x: int(x[0])):
        lines.append(f'    [{int(row_id)}] = {{ id = {item["id"]}, name = {lua_string(item["name"])} }},')

    lines.append("}")
    lines.append("")
    lines.append("-- Location Name to ID")
    lines.append("locations_data.location_name_to_id = {")
    for name, loc_id in sorted(data["location_name_to_id"].items()):
        lines.append(f'    [{lua_string(name)}] = {loc_id},')
    lines.append("}")
    lines.append("")
    lines.append("-- Location ID to Name")
    lines.append("locations_data.location_id_to_name = {")
    for loc_id, name in sorted(data["location_id_to_name"].items(), key=lambda x: int(x[0])):
        lines.append(f'    [{loc_id}] = {lua_string(name)},')
    lines.append("}")
    lines.append("")
    lines.append("return locations_data")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    data = json.loads((repo_root / "ue4ss_mod/FNAFHWArchipelago/locations.json").read_text(encoding="utf-8"))
    out_lua = repo_root / "ue4ss_mod/FNAFHWArchipelago/Scripts/lib/locations_data.lua"
    out_lua.write_text(render(data), encoding="utf-8")
    print(f"Generated {out_lua}!")


if __name__ == "__main__":
    main()
